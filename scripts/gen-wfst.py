"""Generate the immutable H o C graph; normal library builds need no Python."""
import argparse
import math
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]


def generate(subset=None):
    source = (ROOT / "src/codes.h").read_text()
    body = source.split("md_codes[] = {", 1)[1].rsplit("};", 1)[0]
    expression = r'\{\s*"([^"\\]+)"\s*,\s*"([.-]+)"\s*\}'
    entries = re.findall(expression, body)
    if not entries or re.sub(expression, "", body).strip(" \t\r\n,"):
        raise ValueError("unsupported Morse table syntax")
    table = {}
    for text, pattern in entries:
        if len(text.encode("ascii")) > 255:
            raise ValueError("output exceeds ordinal byte range")
        if pattern in table and table[pattern] != text:
            raise ValueError("conflicting Morse pattern")
        if subset is None or text in subset:
            table[pattern] = text
    if subset and set(table.values()) != subset:
        raise ValueError("unknown subset character")
    prefixes = sorted({p[:i] for p in table for i in range(1, len(p) + 1)},
                      key=lambda p: (len(p), p))
    symbols = ["", "*"] + sorted(set(table.values()))
    labels = {text: i for i, text in enumerate(symbols)}
    nodes = [("", 5)]
    ids = {("", 5): 0}
    for p in prefixes:
        classes = [0 if p[-1] == "." else 1]
        if any(p + ch in prefixes for ch in ".-"):
            classes.append(2)
        if p in table:
            classes += [3, 4]
        for k in classes:
            ids[p, k] = len(nodes)
            nodes.append((p, k))
    edges, records = [], []

    def mark_edges(prefix, output=0):
        targets = [(prefix + ch, w) for ch, w in [(".", .58), ("-", .42)]
                   if prefix + ch in prefixes]
        total = 1.0  # C removes illegal paths without renormalizing acoustic priors.
        return [(ids[p, 0 if p[-1] == "." else 1], output, math.log(w / total))
                for p, w in targets]

    for i, (p, k) in enumerate(nodes):
        outgoing = [(i, 0, 0.)]
        label = labels[table[p]] if p in table else 0
        if k == 5:
            outgoing += mark_edges("")
        elif k < 2:
            gaps = [(g, w) for g, w in [(2, .65), (3, .23), (4, .12)]
                    if (p, g) in ids]
            total = 1.0
            outgoing += [(ids[p, g], 0, math.log(w / total)) for g, w in gaps]
        elif k == 2:
            outgoing += mark_edges(p)
        else:
            if k == 4:
                outgoing += [(0, label, 0.)]
            outgoing += mark_edges("", label)
        records.append((len(edges), len(outgoing), label,
                        0 if k == 5 else 1 if k < 2 else 2, k))
        for target, output, weight in outgoing:
            target_class = nodes[target][1]
            input_label = 0 if target_class == 0 else 1 if target_class == 1 else 2
            edges.append((target, input_label, output, weight))
    if len(nodes) >= 65535 or len(edges) >= 65535:
        raise ValueError("graph index overflow")
    lines = ["/* SPDX-License-Identifier: GPL-3.0-or-later */",
             "/* Generated by scripts/gen-wfst.py; edit src/codes.h instead. */",
             "#ifndef MD_WFST_GRAPH_H", "#define MD_WFST_GRAPH_H",
             f"#define MD_WFST_GRAPH_NODES {len(nodes)}",
             f"#define MD_WFST_GRAPH_EDGES {len(edges)}",
             f"#define MD_WFST_GRAPH_SYMBOLS {len(symbols)}",
             f"#define MD_WFST_GRAPH_DEGREE {max(r[1] for r in records)}",
             "/* clang-format off */",
             "static const char *const md_wfst_symbols[] = {"]
    lines += [f'\t"{s}",' for s in symbols]
    lines += ["};", "static const struct md_wfst_node md_wfst_nodes[] = {"]
    lines += ["\t{%d, %d, %d, %d, %d}, /* %s */" % (*r, p or "idle")
              for r, (p, _) in zip(records, nodes)]
    lines += ["};", "static const struct md_wfst_edge md_wfst_edges[] = {"]
    lines += [f"\t{{{t}, {inp}, {out}, {w:.9f}f}}," for t, inp, out, w in edges]
    lines += ["};", "/* clang-format on */", "#endif", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--subset", help="comma-separated output symbols")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = generate(set(args.subset.split(",")) if args.subset else None)
    target = ROOT / "src/wfst_graph.h"
    if args.check:
        if not target.exists() or target.read_text() != content:
            sys.exit("WFST graph is stale; run scripts/gen-wfst.py")
    else:
        target.write_text(content)


if __name__ == "__main__":
    main()
